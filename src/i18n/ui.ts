/** Ruta equivalente en el otro idioma. El español va sin prefijo. */
export function localePath(lang: Locale, path = '/'): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return lang === 'es' ? clean : `/en${clean === '/' ? '/' : clean}`;
}
